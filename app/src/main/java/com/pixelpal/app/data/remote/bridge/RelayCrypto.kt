package com.pixelpal.app.data.remote.bridge

import java.security.MessageDigest
import javax.crypto.Mac
import javax.crypto.SecretKeyFactory
import javax.crypto.spec.PBEKeySpec
import javax.crypto.spec.SecretKeySpec

/**
 * Pairing-code crypto — the **Kotlin twin** of
 * `tools/agent-bridge/pixelpal_bridge/relay_crypto.py`.
 *
 * Both sides must derive byte-identical values, so every constant here is
 * duplicated from the Python module on purpose. If you change one, change the
 * other and re-run both test suites — the cross-language contract is asserted by
 * `RelayCryptoTest` using values captured from the Python implementation.
 *
 * ## Why the code is never transmitted
 *
 * We do not encrypt a secret under the short code and send it; an attacker who
 * captured that blob could grind it offline forever. Instead each side derives
 * the relay key locally:
 *
 *     relayKey = PBKDF2-HMAC-SHA256(code, "pixelpal-relay-v1", 260_000)
 *
 * Firestore only ever holds `HMAC(relayKey, "pixelpal-handshake")`, which proves
 * possession of the code without revealing it or making the code recoverable.
 */
object RelayCrypto {

    /** No ambiguous glyphs (0/O, 1/I/L, 2/Z, 5/S absent). */
    const val ALPHABET = "346789ABCDEFGHJKMNPQRTUVWXY"
    const val CODE_LENGTH = 9
    const val GROUP_SIZE = 3

    private const val PBKDF2_ITERATIONS = 260_000
    private const val KEY_BITS = 256
    private val SALT = "pixelpal-relay-v1".toByteArray(Charsets.UTF_8)
    private val VERIFIER_LABEL = "pixelpal-handshake".toByteArray(Charsets.UTF_8)
    private const val HAND_MAC = "HmacSHA256"

    /**
     * Canonicalise user input. Returns null when the text cannot be a valid
     * code, so the UI can say "that code looks wrong" instead of failing later.
     *
     * Deliberately does NOT auto-correct ambiguous glyphs: a typed `O` is a real
     * transcription error, and silently rewriting it would pair with the wrong
     * key and fail confusingly.
     */
    fun normalizeCode(input: String?): String? {
        if (input.isNullOrBlank()) return null
        val cleaned = input.trim().uppercase().replace("-", "").replace(" ", "")
        if (cleaned.length != CODE_LENGTH) return null
        if (!cleaned.all { it in ALPHABET }) return null
        return cleaned
    }

    /** Re-group a normalised code for display: "ABC-DEF-GHI". */
    fun formatCode(normalized: String): String =
        normalized.chunked(GROUP_SIZE).joinToString("-")

    /** A fresh code, generated by the bridge (never by the app). */
    fun generateCode(): String =
        (1..CODE_LENGTH).map { ALPHABET.random() }.joinToString("").let(::formatCode)

    /** pair code -> 32-byte relay key. Identical to the Python implementation. */
    fun deriveRelayKey(normalizedCode: String): ByteArray {
        require(normalizeCode(normalizedCode) != null) { "invalid pairing code" }
        val spec = PBEKeySpec(
            normalizedCode.toCharArray(),
            SALT,
            PBKDF2_ITERATIONS,
            KEY_BITS
        )
        return SecretKeyFactory.getInstance("PBKDF2WithHmacSHA256")
            .generateSecret(spec)
            .encoded
    }

    /** Public proof-of-key stored in Firestore. Reveals nothing about the key. */
    fun verifier(relayKey: ByteArray): String {
        val mac = Mac.getInstance(HAND_MAC)
        mac.init(SecretKeySpec(relayKey, HAND_MAC))
        return mac.doFinal(VERIFIER_LABEL).toHex()
    }

    /**
     * Firestore document id, derived from the code.
     *
     * Hashed so that reading the relays collection never hands anyone a list of
     * valid codes. Truncated to 32 hex chars — collision-safe and URL-friendly.
     */
    fun lookupId(normalizedCode: String): String =
        MessageDigest.getInstance("SHA-256")
            .digest(normalizedCode.toByteArray(Charsets.UTF_8))
            .toHex()
            .take(32)

    /**
     * Constant-time check that a peer's verifier matches ours.
     *
     * Comparison is folded so a wrong code cannot be narrowed down by timing.
     */
    fun verify(relayKey: ByteArray, presentedVerifier: String?): Boolean {
        if (presentedVerifier.isNullOrEmpty()) return false
        val expected = verifier(relayKey)
        val actual = presentedVerifier.lowercase()
        if (expected.length != actual.length) return false
        var difference = 0
        for (index in expected.indices) {
            difference = difference or (expected[index].code xor actual[index].code)
        }
        return difference == 0
    }

    private fun ByteArray.toHex(): String =
        joinToString("") { byte -> "%02x".format(byte) }
}
